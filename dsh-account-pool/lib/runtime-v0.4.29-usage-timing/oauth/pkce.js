/**
 * Leaf module: the PKCE / encoding / token-endpoint primitives.
 *
 * These live in their own file for one structural reason: both `lib/oauth.js`
 * (the public surface, re-exported by the provider table) and
 * `lib/oauth/providers.js` (which imports them) need them. Putting them in
 * `oauth.js` made that a cycle — legal in ESM, but the kind of legal that
 * resolves to `undefined` in the middle of a token exchange when the entry point
 * changes. A leaf has no such failure mode.
 *
 * No imports beyond `node:crypto`; no state; `fetch` always injected.
 */
import { createHash, randomBytes } from 'node:crypto';

/** base64url, unpadded — RFC 7636 §A requires it for the challenge. */
export function base64url(buffer) {
  return Buffer.from(buffer).toString('base64').replaceAll('+', '-').replaceAll('/', '_').replaceAll('=', '');
}

/**
 * A PKCE pair.
 *
 * `S256` only, never `plain`: the verifier travels through the browser's address
 * bar as part of the redirect, so a proxy or a browser history entry that sees
 * it must not be able to replay it.
 *
 * `encoding` is per-vendor and NOT cosmetic. RFC 7636 §4.1 allows any of
 * `[A-Za-z0-9-._~]`, so base64url and hex are both legal verifiers — but the
 * vendor hashes whatever string it is sent, which means the verifier and the
 * challenge must be generated by the SAME client that will redeem them. OpenAI's
 * client mints a hex verifier and a base64url challenge; everyone else here uses
 * base64url for both. Sending the wrong one is an `invalid_grant` with nothing
 * local to point at.
 *
 * @param options.encoding - `'base64url'` (default) or `'hex'`.
 * @param options.random - raw bytes, injectable so tests can assert the exact
 *   challenge for a known verifier (RFC 7636 Appendix B).
 */
export function pkce(options = {}) {
  const encoding = String(options.encoding ?? 'base64url');
  const bytes = options.random ?? randomBytes(options.bytes ?? (encoding === 'hex' ? 64 : 32));
  const verifier = encoding === 'hex' ? Buffer.from(bytes).toString('hex') : base64url(bytes);
  const challenge = base64url(createHash('sha256').update(verifier).digest());
  return { verifier, challenge, method: 'S256' };
}

/** An opaque anti-CSRF nonce. `encoding` is per-vendor: see the providers table. */
export function state(random = randomBytes(16), encoding = 'base64url') {
  return String(encoding) === 'hex' ? Buffer.from(random).toString('hex') : base64url(random);
}

/**
 * A fresh flow id, prefixed with the provider so a page listing several pending
 * logins shows which is which without a second lookup.
 *
 * It lives here rather than next to the flow store because the ENGINE is what
 * mints ids, and the engine can only import this leaf module — importing the
 * store's own file would rebuild the cycle this module exists to avoid.
 */
export function newFlowId(providerId, random = randomBytes(8)) {
  return `${providerId}-${base64url(random).slice(0, 12)}`;
}

/**
 * Pull the authorization code out of whatever the operator pasted.
 *
 * Three shapes occur in practice and all three are accepted, because asking an
 * operator to hand-extract a query parameter from an address bar is how a login
 * ends up "randomly failing":
 *   - a bare code;
 *   - `code#state` (the OAuth 2.0 for Native Apps form some vendors use);
 *   - the whole redirect URL, which is what the address bar actually shows.
 *
 * @returns `{ code, state }` with `state` possibly `undefined` for a bare code.
 */
export function parseAuthInput(input) {
  const text = String(input ?? '').trim();
  if (text === '') return { code: '', state: undefined };

  if (/^https?:\/\//i.test(text)) {
    try {
      const url = new URL(text);
      const code = url.searchParams.get('code') ?? '';
      const nonce = url.searchParams.get('state') ?? undefined;
      if (code !== '' || nonce !== undefined) return { code, state: nonce };
    } catch { /* not a URL after all: fall through to the literal forms */ }
  }
  if (text.includes('#')) {
    const [code, part] = text.split('#', 2);
    return { code: code.trim(), state: part?.trim() || undefined };
  }
  if (text.includes('code=')) {
    const params = new URLSearchParams(text.replace(/^[^?]*\?/, ''));
    const code = params.get('code') ?? '';
    if (code !== '') return { code, state: params.get('state') ?? undefined };
  }
  return { code: text, state: undefined };
}

/**
 * Read `code`/`state`/`error` out of callback parameters.
 *
 * The vendor's own error is surfaced verbatim: `access_denied` and
 * `invalid_scope` mean completely different things to the operator, and
 * collapsing them into "login failed" throws away the only diagnostic there is.
 */
export function readCallbackParams(params = {}) {
  const error = typeof params.error === 'string' && params.error !== '' ? params.error : undefined;
  if (error !== undefined) {
    return {
      ok: false,
      error,
      errorDescription: typeof params.error_description === 'string' ? params.error_description : '',
    };
  }
  const code = typeof params.code === 'string' && params.code !== '' ? params.code : undefined;
  if (code === undefined) return { ok: false, error: 'missing_code', errorDescription: 'the callback carried no code' };
  return { ok: true, code, state: typeof params.state === 'string' && params.state !== '' ? params.state : undefined };
}

/** `application/x-www-form-urlencoded` body from a plain object, skipping null/undefined. */
export function formEncode(fields) {
  const params = new URLSearchParams();
  for (const [key, value] of Object.entries(fields)) {
    if (value === undefined || value === null) continue;
    params.set(key, String(value));
  }
  return params;
}

/** Append query parameters to a URL that may already carry some. */
export function withQuery(url, params) {
  const parsed = new URL(url);
  for (const [key, value] of Object.entries(params)) {
    if (value === undefined || value === null) continue;
    parsed.searchParams.set(key, String(value));
  }
  return parsed.toString();
}

/** Raised when the far end refuses a token exchange; carries the vendor's own words. */
export class OAuthError extends Error {
  constructor(message, details = {}) {
    super(message);
    this.name = 'OAuthError';
    this.code = details.code ?? 'oauth-failed';
    this.status = details.status;
    this.detail = details.detail;
  }
}

/**
 * POST a token request and return the JSON body, or throw with the vendor's own
 * error text.
 *
 * Both encodings are supported because the vendors disagree — Google and OpenAI
 * take form encoding, Anthropic takes JSON — and the caller declares which.
 * Guessing would turn a content-type mismatch into an opaque 400.
 */
export async function postToken(fetchImpl, url, { body, headers = {}, method = 'POST' }) {
  const response = await fetchImpl(url, { method, headers, body });
  const text = await response.text();
  let parsed;
  try {
    parsed = JSON.parse(text);
  } catch {
    parsed = undefined;
  }
  if (!response.ok) {
    const detail = parsed?.error_description ?? parsed?.error?.message ?? parsed?.error ?? text.slice(0, 300);
    throw new OAuthError(`token endpoint ${String(response.status)}: ${String(detail)}`, {
      code: typeof parsed?.error === 'string' ? parsed.error : `http-${String(response.status)}`,
      status: response.status,
      detail,
    });
  }
  if (parsed === undefined || typeof parsed !== 'object') {
    throw new OAuthError('token endpoint did not return JSON', { code: 'invalid-token-response' });
  }
  return parsed;
}

/**
 * Milliseconds until an access token expires, from the vendor's `expires_in`, as
 * an absolute ISO instant.
 *
 * `null` when the vendor does not say — an unknown window must not be invented,
 * because the value is what a later refresh decision reads.
 */
export function expiresAtFrom(payload, nowMs) {
  const seconds = Number(payload?.expires_in);
  if (!Number.isFinite(seconds) || seconds <= 0) return null;
  return new Date(nowMs + seconds * 1000).toISOString();
}

/** Decoded JWT payload, or `null` when the value is not a decodable JWT. */
export function decodeJwtPayload(jwt) {
  if (typeof jwt !== 'string') return null;
  const parts = jwt.split('.');
  if (parts.length < 2) return null;
  try {
    const json = Buffer.from(parts[1].replaceAll('-', '+').replaceAll('_', '/'), 'base64').toString('utf8');
    const parsed = JSON.parse(json);
    return parsed !== null && typeof parsed === 'object' ? parsed : null;
  } catch {
    return null;
  }
}

function firstString(values) {
  for (const value of values) {
    if (typeof value === 'string' && value.trim() !== '') return value.trim();
  }
  return undefined;
}

/**
 * Pull a human label and the account's identity out of whatever the vendor
 * returned: an `id_token` JWT payload, or plain fields on the token response.
 *
 * Decoding the JWT here is reading our OWN freshly issued token, not verifying
 * one — signature verification belongs to the party that will later accept it,
 * and these values drive a display label and a default account id only.
 */
export function identityFrom(payload) {
  const claims = decodeJwtPayload(payload?.id_token) ?? {};
  const email = firstString([claims.email, payload?.email, claims.preferred_username]);
  const accountId = firstString([claims.sub, payload?.account_id, payload?.user_id]);
  const plan = firstString([payload?.plan_type, claims.plan_type, claims.chatgpt_plan_type]);
  return { email: email ?? null, accountId: accountId ?? null, plan: plan ?? null, claims };
}

